import { afterEach, describe, expect, it, vi } from 'vitest';
import { mkdtemp, mkdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, win32 } from 'node:path';
import { JetBrainsIdeImporter, JetBrainsIdeImportError } from '../src/main/jetbrains-ide-import';
import { decodeWindowsJavaPreference, readWindowsJetBrainsPreferences, windowsJetBrainsPreferencesHelper, type JetBrainsPreferenceValues, type WindowsJetBrainsPreferencesRunner } from '../src/main/jetbrains-ide-windows';

const roots: string[] = [];
afterEach(async () => { for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); });
const claims = { user_id: 'fixture-user', full_name: 'Windows 用户', jba_login: 'fixture.login', exp: 1577836800 };
const header = Buffer.from('{"alg":"RS256"}').toString('base64url');
const token = (changes: Partial<typeof claims> = {}) => `${header}.${Buffer.from(JSON.stringify({ ...claims, ...changes })).toString('base64url')}.c3ludGhldGljX3NpZ25hdHVyZQ`;
function wrap(value: string): string {
  const bytes = Buffer.from(value), mask = Buffer.from('The Drive to Develop.');
  for (let i = 0; i < bytes.length; i++) bytes[i] ^= mask[i % mask.length];
  return bytes.toString('base64');
}
const values = (changes: Partial<typeof claims> = {}): JetBrainsPreferenceValues => ({ idtoken: wrap(token(changes)), userid: wrap(changes.user_id ?? claims.user_id), userlogin: wrap('fixture.login') });
const license = (id = 'fixture-license', logout = false) => `<application><component name="AipLicense"><option name="licenseId" value="${id}"/><option name="isForciblyLoggedOut" value="${logout}"/></component><component name="Unrelated"><option name="apiKey" value="SYNTHETIC_PRIVATE_OTHER_SETTING"/></component></application>`;

async function fixture(explicitAppData = true) {
  const home = await mkdtemp(join(tmpdir(), 'modeldock IDE 中文 & space-')); roots.push(home);
  const appData = explicitAppData ? join(home, '自定义 Roaming') : join(home, 'AppData', 'Roaming');
  const profile = join(appData, 'JetBrains', 'IntelliJIdea2026.2', 'options', 'other.xml');
  await mkdir(join(appData, 'JetBrains', 'IntelliJIdea2026.2', 'options'), { recursive: true }); await writeFile(profile, license());
  let current = values(), clock = 1_800_000_000_000;
  const readWindowsPreferences = vi.fn(async () => structuredClone(current));
  const options = { homeDir: home, platform: 'win32' as const, env: explicitAppData ? { APPDATA: appData, XDG_CONFIG_HOME: join(home, 'ignored-linux') } : {}, readWindowsPreferences, now: () => clock };
  const reader = new JetBrainsIdeImporter(options);
  return { home, appData, profile, reader, options, readWindowsPreferences, change: (next: JetBrainsPreferenceValues) => { current = next; }, advance: () => { clock += 5 * 60_000; } };
}

describe('fixed read-only Windows JBR preference transport', () => {
  it('decodes an independent installed JBR golden with Chinese, surrogate pairs, MIME whitespace, case and slash escaping', () => {
    // Generated by IDEA 2026.2.4's JBR 25.0.4.1 private pure conversion methods;
    // no Preferences node was opened or written by the independent producer.
    const source = Buffer.from('QVphejA5Ky89DQoJXCDnlKjmiLcg8J+YgA==', 'base64').toString('utf8');
    const native = Buffer.from('L0EvWmF6MDkrXD0vdTAwMGQvdTAwMGEvdTAwMDkvLyAvdTc1MjgvdTYyMzcgL3VkODNkL3VkZTAw', 'base64').toString('ascii');
    expect(source).toBe('AZaz09+/=\r\n\t\\ 用户 😀');
    expect(decodeWindowsJavaPreference(native)).toBe(source);
    expect(decodeWindowsJavaPreference('')).toBe('');
    for (const raw of ['/a', '/', '/u000', '/uZZZZ', 'A', '用户', 'x'.repeat(393217), '/u0000'.repeat(65537)]) expect(() => decodeWindowsJavaPreference(raw)).toThrow('无法安全读取');
  });
  it('uses one absolute hidden bounded PowerShell call with a fixed Registry64 query and no value arguments', async () => {
    const execute = vi.fn<WindowsJetBrainsPreferencesRunner>(async () => JSON.stringify({ ok: true, values: { idtoken: '/A/Zaz09+\\=/u000d/u000a' } }));
    expect(await readWindowsJetBrainsPreferences(execute)).toEqual({ idtoken: 'AZaz09+/=\r\n' });
    expect(execute).toHaveBeenCalledTimes(1);
    const [file, args, options] = execute.mock.calls[0];
    expect(win32.isAbsolute(file)).toBe(true); expect(file).toMatch(/System32[\\/]WindowsPowerShell[\\/]v1\.0[\\/]powershell\.exe$/);
    expect(args.slice(0, 4)).toEqual(['-NoLogo', '-NoProfile', '-NonInteractive', '-EncodedCommand']);
    expect(Buffer.from(args[4], 'base64').toString('utf16le')).toBe(windowsJetBrainsPreferencesHelper);
    expect(options).toEqual({ timeout: 10000, maxBuffer: 2363392, windowsHide: true, encoding: 'utf8' });
    expect(windowsJetBrainsPreferencesHelper).toContain('Software\\JavaSoft\\Prefs\\jetbrains\\jetprofile');
    expect(windowsJetBrainsPreferencesHelper).toContain('0,0x101,out key');
    expect(windowsJetBrainsPreferencesHelper).not.toMatch(/RegSet|CreateSubKey|OpenSubKey|RegEnum|PasswordSafe|Registry32/);
  });
  it('returns an empty result for a missing native node and redacts errors, oversized data, extra keys and malformed values', async () => {
    expect(await readWindowsJetBrainsPreferences(async () => '{"ok":true,"values":{}}')).toEqual({});
    for (const raw of ['SYNTHETIC_PRIVATE_MALFORMED', '{"ok":false}', JSON.stringify({ ok: true, values: { idtoken: 1 } }), JSON.stringify({ ok: true, values: { password: 'SYNTHETIC_PRIVATE' } }), JSON.stringify({ ok: true, values: {}, unexpected: 'SYNTHETIC_PRIVATE' }), JSON.stringify({ ok: true, values: { idtoken: 'x'.repeat(393217) } }), 'x'.repeat(2363393)]) {
      const failure = await readWindowsJetBrainsPreferences(async () => raw).catch(error => error as Error);
      expect(failure).toBeInstanceOf(Error); expect(String(failure)).toContain('无法安全读取'); expect(String(failure)).not.toContain('SYNTHETIC_PRIVATE');
    }
    await expect(readWindowsJetBrainsPreferences(async () => { throw new Error('SYNTHETIC_PRIVATE_REGISTRY_ERROR'); })).rejects.toThrow('无法安全读取');
  });
});

describe('explicit Windows IDE / built-in Air account selection', () => {
  it.each([true, false])('uses the native fixed account and %s explicit APPDATA path, preserves source files and never infers cloud authorization', async explicit => {
    const f = await fixture(explicit); expect(f.readWindowsPreferences).not.toHaveBeenCalled(); const before = await readFile(f.profile);
    const candidates = await f.reader.listCandidates(); expect(candidates).toHaveLength(1);
    expect(candidates[0]).toMatchObject({ client: 'jetbrains-ide', product: 'intellij-idea', accountId: 'fixture-user', accountLabel: 'Windows 用户' });
    expect(JSON.stringify(candidates)).not.toMatch(/eyJ|idtoken|SYNTHETIC_PRIVATE|fixture-license|other\.xml/);
    const credential = await f.reader.readCredentials(candidates[0].id);
    expect(credential).toMatchObject({ authorization: 'unverified', tokenType: 'jba-id-token', idToken: token(), licenseId: 'fixture-license', accountId: 'fixture-user' });
    expect(credential).not.toHaveProperty('accessToken'); expect(credential).not.toHaveProperty('expiresAt');
    expect(f.readWindowsPreferences).toHaveBeenCalledTimes(3); expect(await readFile(f.profile)).toEqual(before);
  });
  it('offers only fixed supported Windows profile licenses and ignores retained old and independent Air sources', async () => {
    const f = await fixture();
    for (const name of ['WebStorm2026.2', 'Rider2026.2', 'PyCharm2026.2', 'IntelliJIdea2026.1', 'Air']) {
      const dir = join(f.appData, 'JetBrains', name, 'options'); await mkdir(dir, { recursive: true }); await writeFile(join(dir, 'other.xml'), license('fixture-' + name));
    }
    const first = await f.reader.listCandidates(), second = await f.reader.listCandidates();
    expect(first.map(item => item.product)).toEqual(['intellij-idea', 'webstorm', 'rider', 'pycharm']);
    expect(first.map(item => item.sourceIdentity)).toEqual(second.map(item => item.sourceIdentity));
    expect(first.map(item => item.id)).not.toEqual(second.map(item => item.id));
  });
  it('never falls back to Linux preferences, another registry view or an old license after missing or unreadable native credentials', async () => {
    const f = await fixture(); const decoy = join(f.home, '.java', '.userPrefs', 'jetbrains', 'jetprofile'); await mkdir(decoy, { recursive: true }); await writeFile(join(decoy, 'prefs.xml'), 'SYNTHETIC_PRIVATE_DECOY');
    f.change({}); expect(await f.reader.listCandidates()).toEqual([]);
    f.readWindowsPreferences.mockRejectedValueOnce(new Error('SYNTHETIC_PRIVATE_BACKEND'));
    const failure = await f.reader.listCandidates().catch(error => error as Error);
    expect(failure).toBeInstanceOf(JetBrainsIdeImportError); expect(String(failure)).toContain('注册表读取权限'); expect(String(failure)).not.toContain('SYNTHETIC_PRIVATE');
    f.change(values()); await writeFile(f.profile, license('fixture-license', true)); await expect(f.reader.listCandidates()).rejects.toThrow('选择本人许可证');
  });
  it.each(['account', 'license', 'logout', 'expiry'] as const)('rejects a changed %s after preview', async change => {
    const f = await fixture(); const [candidate] = await f.reader.listCandidates();
    if (change === 'account') f.change(values({ user_id: 'switched-account' }));
    else if (change === 'expiry') f.advance();
    else await writeFile(f.profile, license(change === 'license' ? 'switched-license' : 'fixture-license', change === 'logout'));
    await expect(f.reader.readCredentials(candidate.id)).rejects.toThrow(/切换|变化|过期/);
  });
  it('brackets registry and license reads to reject an account switch during confirmation', async () => {
    const f = await fixture(); const [candidate] = await f.reader.listCandidates();
    f.readWindowsPreferences.mockResolvedValueOnce(values()).mockResolvedValueOnce(values({ user_id: 'switched-during-read' }));
    await expect(f.reader.readCredentials(candidate.id)).rejects.toThrow('切换');
  });
  it('rejects relative APPDATA, mismatched native identities and oversized license files', async () => {
    const f = await fixture();
    await expect(new JetBrainsIdeImporter({ ...f.options, env: { APPDATA: 'relative' } }).listCandidates()).rejects.toThrow('格式无法识别');
    f.change({ ...values(), userid: wrap('another-user') }); await expect(f.reader.listCandidates()).rejects.toThrow('账号信息不一致');
    f.change(values()); await writeFile(f.profile, 'x'.repeat(1048577)); await expect(f.reader.listCandidates()).rejects.toThrow(JetBrainsIdeImportError);
  });
  it('refuses a redirected profile directory using a Windows junction without requiring file-symlink privileges', async () => {
    const f = await fixture(), redirected = join(f.home, 'foreign-options'); await mkdir(redirected); await writeFile(join(redirected, 'other.xml'), license());
    const optionsDir = join(f.appData, 'JetBrains', 'IntelliJIdea2026.2', 'options'); await rm(optionsDir, { recursive: true }); await symlink(redirected, optionsDir, 'junction');
    await expect(f.reader.listCandidates()).rejects.toThrow(JetBrainsIdeImportError); expect(await readFile(join(redirected, 'other.xml'), 'utf8')).toBe(license());
  });
});
